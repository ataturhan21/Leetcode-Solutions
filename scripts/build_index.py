#!/usr/bin/env python3
"""Build language indexes without importing or executing solution files."""

import argparse
import re
from pathlib import Path
from urllib.parse import quote

LANGUAGES = (
    (".py", "Python", "solutions-python.md"),
    (".sql", "SQL", "solutions-sql.md"),
    (".js", "JavaScript", "solutions-javascript.md"),
)


def markdown_label(value):
    return value.replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]").replace("|", "\\|")


def build_indexes(root):
    folders = sorted(
        (path for path in root.iterdir() if path.is_dir() and re.match(r"^\d+-", path.name)),
        key=lambda path: (int(path.name.split("-", 1)[0]), path.name),
    )
    indexes = {}
    for extension, language, filename in LANGUAGES:
        lines = [
            f"# {language} solutions",
            "",
            "[Back to repository overview](../README.md)",
            "",
            "Generated by `python3 scripts/build_index.py`. Directory identifiers follow the repository's existing names.",
            "",
            "| Problem directory | Solution |",
            "| --- | --- |",
        ]
        for folder in folders:
            for solution in sorted(folder.rglob("*" + extension)):
                if not solution.is_file():
                    continue
                directory_url = "../" + quote(folder.name, safe="") + "/"
                solution_url = "../" + quote(solution.relative_to(root).as_posix(), safe="/")
                lines.append(
                    f"| [{markdown_label(folder.name)}]({directory_url}) | "
                    f"[{markdown_label(solution.name)}]({solution_url}) |"
                )
        indexes[Path("docs") / filename] = "\n".join(lines) + "\n"
    return indexes


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if committed indexes need regeneration")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    changed = []
    for relative, content in build_indexes(root).items():
        target = root / relative
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != content:
                changed.append(str(relative))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
    if changed:
        parser.exit(1, "Regenerate indexes with python3 scripts/build_index.py: " + ", ".join(changed) + "\n")


if __name__ == "__main__":
    main()
